% 対象のモデル名を指定します
% （bdroot は現在開いてアクティブになっているモデル名を取得します）
mdl = bdroot; 

% ----------------------------------------------------
% シミュレーション時間
% ----------------------------------------------------
set_param(mdl, 'StartTime', '0.0');
set_param(mdl, 'StopTime',  'SimEnd');

% ----------------------------------------------------
% ソルバーの選択
% ----------------------------------------------------
% タイプ: 固定ステップ
set_param(mdl, 'SolverType', 'Fixed-step'); 
% ソルバー: ode4 (Runge-Kutta)
set_param(mdl, 'Solver',     'ode4');       

% ----------------------------------------------------
% ソルバーの詳細
% ----------------------------------------------------
% 固定ステップ サイズ (基本サンプル時間): dt
set_param(mdl, 'FixedStep',  'dt');         

% ----------------------------------------------------
% タスクとサンプル時間オプション
% ----------------------------------------------------
% 周期的なサンプル時間の制約: 制約なし
set_param(mdl, 'SampleTimeConstraint',  'Unconstrained'); 
% 各離散レートを個別のタスクとして扱う: チェックなし
set_param(mdl, 'EnableMultiTasking',    'off');           
% ターゲット上でタスクの同時実行を許可: チェックなし
set_param(mdl, 'ConcurrentTasks',       'off');           
% データ転送に対するレート変換を自動的に取り扱う: チェックなし
set_param(mdl, 'AutoInsertRateTranBlk', 'off');           
% 優先順位の値が高いほどタスクの優先順位が高いことを示す: チェックなし
set_param(mdl, 'PositivePriorityOrder', 'off');           

disp('コンフィギュレーション パラメーター（ソルバー）の設定が完了しました。');